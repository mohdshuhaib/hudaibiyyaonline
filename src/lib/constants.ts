export function formatPermanentAddress(member: {
  house_name: string;
  place_po: string;
  post_office?: string | null;
  district: string;
  pincode: string;
}): string {
  const parts = [
    member.house_name ? `${member.house_name.trim()} (H)` : "",
    member.place_po?.trim() || "",
    member.post_office?.trim() || "",
    member.district?.trim() || "",
    member.pincode ? `PIN ${member.pincode.trim()}` : "",
  ].filter(Boolean);
  return parts.join(", ");
}

